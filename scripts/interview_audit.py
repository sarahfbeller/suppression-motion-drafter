#!/usr/bin/env python3
"""Report how the interview behaves across many simulated cases, for reviewing the decision tree.

Usage (from the repo root):
    python3 scripts/interview_audit.py [--per-issue 200] [--out review/interview-audit.md]

For each question: how often it's asked, and which encounter events were present in every case where
it was asked. A question whose prompt assumes something (a stopped vehicle, a breath test) but is
asked without that event points to a condition that doesn't state its precondition. Also reports
interview lengths and any question a condition uses but no simulated interview reached.
Prints to stdout unless --out is given.
"""
import os
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import engine as E  # noqa: E402
import simulate as S  # noqa: E402


def build(root, per_issue):
    config, questions, issues = E.load_repo(root)
    asked_with = {}  # question -> intersection of events present when it was asked
    groups = config.get("event_groups", {})
    group_with = {}  # question -> event groups with at least one member present every time it was asked
    times = {}
    lengths = {}  # issue id (or None for random cases) -> interview lengths after the top questions
    for target, full in S.cases(questions, issues, per_issue, seed=1):
        _, asked = S.run_interview(issues, full)
        events = set(full[E.ENCOUNTER_EVENTS] or [])
        for qid in asked:
            times[qid] = times.get(qid, 0) + 1
            asked_with[qid] = asked_with[qid] & events if qid in asked_with else set(events)
            present = {g for g, members in groups.items() if events & set(members)}
            group_with[qid] = group_with[qid] & present if qid in group_with else present
        lengths.setdefault(target, []).append(len(asked) - len(E.TOP_QUESTIONS))

    used = set()
    for issue in issues:
        trig = issue["trigger"]
        for c in ([trig["match_condition"]] + [n["when"] for n in trig.get("review_conditions", [])]
                  + [n["when"] for n in trig.get("excluded_explanations", [])]
                  + [p["when"] for p in issue["law_paragraphs"] if "when" in p]):
            used |= E.condition_questions(c)

    n_cases = sum(len(v) for v in lengths.values())
    out = ["# Interview audit", "",
           f"Generated by `scripts/interview_audit.py` from {n_cases} simulated cases ({per_issue} with each "
           f"issue's event happening, plus {per_issue} fully random). Don't edit; regenerate.", "",
           "## Questions", "",
           "*Always with* lists the encounter events present in **every** simulated case where the question "
           "was asked. If a question's prompt assumes an event that isn't listed (e.g. a question about "
           "\"the stopped vehicle\" without `vehicle_stop`), some condition using it is missing that "
           "precondition. *Always with one of* names the event groups (`content/config.json`) that had at "
           "least one event present every time.", "",
           "| Question | Asked in | Always with | Always with one of | Prompt |", "|---|---|---|---|---|"]
    for qid, q in questions.items():
        if qid in E.TOP_QUESTIONS or qid not in times:
            continue
        always = ", ".join(f"`{e}`" for e in sorted(asked_with[qid])) or "—"
        one_of = ", ".join(f"`{g}`" for g in sorted(group_with[qid])) or "—"
        out.append(f"| `{qid}` | {times[qid]} | {always} | {one_of} | {q['prompt']} |")
    never = sorted(q for q in used if q not in times and q not in E.TOP_QUESTIONS)
    out += ["", "## Used by a condition but never asked", ""]
    out += [f"- `{q}`" for q in never] if never else ["None."]

    out += ["", "## Interview length", "",
            "Questions asked after the three opening questions.", "",
            "| Cases | Mean | Median | Max |", "|---|---|---|---|"]
    for target in [i["id"] for i in issues] + [None]:
        ls = lengths.get(target)
        if ls:
            name = f"`{target}` event happened" if target else "fully random"
            out.append(f"| {name} | {statistics.mean(ls):.1f} | {statistics.median(ls):g} | {max(ls)} |")
    return "\n".join(out) + "\n"


def main(argv):
    per = int(argv[argv.index("--per-issue") + 1]) if "--per-issue" in argv else 200
    text = build(os.getcwd(), per)
    if "--out" in argv:
        path = argv[argv.index("--out") + 1]
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {path}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
